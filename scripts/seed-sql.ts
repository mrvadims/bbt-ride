// Prints the first-run data (run: node scripts/seed-sql.ts > migrations/0003_seed.sql):
// the start spots and route library from data/seed.json, and the default kit chart.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { DEFAULT_KIT } from "../shared/kit.ts";

const seed = JSON.parse(readFileSync(join(import.meta.dirname, "..", "data/seed.json"), "utf8")) as {
  spots: { id: string; name: string; lat: number; lng: number; maps_url: string; note: string }[];
  routes: { id: number }[];
  group_bbt_route_ids: number[];
};
const q = (v: string | number) => (typeof v === "number" ? String(v) : `'${v.replaceAll("'", "''")}'`);
const now = "2026-10-11T00:00:00.000Z";

const lines = ["-- Generated by scripts/seed-sql.ts from data/seed.json and shared/kit.ts. Do not edit by hand."];
for (const s of seed.spots) {
  lines.push(
    `insert into spots (id, name, lat, lng, maps_url, note, created_at) values (${[s.id, s.name, s.lat, s.lng, s.maps_url, s.note, now].map(q).join(", ")});`,
  );
}
const library = [...new Set([...seed.routes.map((r) => r.id), ...seed.group_bbt_route_ids])];
for (const id of library) lines.push(`insert into route_cache (rwgps_route_id, in_library) values (${id}, 1);`);
DEFAULT_KIT.forEach((b, i) => {
  lines.push(
    `insert into kit_bands (min_feel_f, name, items_json, sort) values (${[b.minFeel, b.name, JSON.stringify(b.items), i].map(q).join(", ")});`,
  );
});
console.log(lines.join("\n"));
