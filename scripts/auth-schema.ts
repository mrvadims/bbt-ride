// Prints the SQL for Better Auth's tables with our plugins (run: node scripts/auth-schema.ts > migrations/0001_auth.sql).
// Uses an in-memory SQLite database so no D1 connection is needed.
import { DatabaseSync } from "node:sqlite";
import { getMigrations } from "better-auth/db/migration";
import { authPlugins, RATE_LIMIT } from "../worker/auth-plugins.ts";

const { compileMigrations } = await getMigrations({
  database: new DatabaseSync(":memory:"),
  emailAndPassword: { enabled: true },
  socialProviders: { google: { clientId: "-", clientSecret: "-" } },
  plugins: authPlugins(),
  rateLimit: RATE_LIMIT,
});
console.log(
  `-- Generated by scripts/auth-schema.ts (Better Auth tables). Do not edit by hand.\n${await compileMigrations()}`,
);
